    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        int index = tabelMahasiswa.getSelectedRow();
        
        if(index == -1) return;
        
        String nim = txtNIM.getText();
        String nama = txtNama.getText();
        String tmpLahir = txtTmpLahir.getText();
        
        if(calTglLahir.getDate() == null) return;
        
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String tglLahir = sdf.format(calTglLahir.getDate());
        String jurusan = cboJurusan.getSelectedItem().toString();
        
        try{
            Connection c = KoneksiDB.getConnection();
            String query = """
                           UPDATE tbMahasiswa 
                           SET nim = ?, nama = ?,tmpLahir = ?,tglLahir = ?,jurusan = ? 
                           WHERE nim = ?
                           """;
            PreparedStatement p = c.prepareStatement(query);
            
            p.setString(1,nim);
            p.setString(2,nama);
            p.setString(3,tmpLahir);
            p.setDate(4,konversiDate(calTglLahir.getDate()));
            p.setString(5,jurusan);
            p.setString(6,nim);
           
            
            
            p.executeUpdate();
            p.close();
        } catch(SQLException e){
            e.printStackTrace();
            System.out.println("Error when Changing data");
        } finally{
            model.setValueAt(nim,index,0);
            model.setValueAt(nama,index,1);
            model.setValueAt(tmpLahir,index,2);
            model.setValueAt(tglLahir,index,3);
            model.setValueAt(jurusan,index,4);
            
            tabelMahasiswa.setModel(model);
            
            setKolomTabel();
        }
        
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        int index = tabelMahasiswa.getSelectedRow();
        
        if(index == -1) return;
        
        String nim = (String) model.getValueAt(index, 0);
        
        try{
            Connection c = KoneksiDB.getConnection();
            String query = "DELETE FROM tbMahasiswa WHERE nim =?";
            
            PreparedStatement p = c.prepareStatement(query);
            p.setString(1,nim);
            p.executeUpdate();
            p.close();
        } catch( SQLException e){
            e.printStackTrace();
            System.out.println("Error when deleting data");
        } finally{
            model.removeRow(index);
            
            tabelMahasiswa.setModel(model);
        }
        
    }//GEN-LAST:event_btnHapusActionPerformed

    private void tabelMahasiswaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelMahasiswaMouseClicked
        // TODO add your handling code here:
        int index = tabelMahasiswa.getSelectedRow();
        
        if(index == -1) return;
        
        String nim = (String) tabelMahasiswa.getValueAt(index, 0);
        String nama = (String) tabelMahasiswa.getValueAt(index, 1);
        String tmpLahir = (String) tabelMahasiswa.getValueAt(index, 2);
        String tglLahir = (String) tabelMahasiswa.getValueAt(index, 3);
        String jurusan = (String) tabelMahasiswa.getValueAt(index, 4);
        
        txtNIM.setText(nim);
        txtNama.setText(nama);
        txtTmpLahir.setText(tmpLahir);
        
        try{
            java.util.Date tanggal = new SimpleDateFormat("yyyy-MM-dd")
            .parse(tglLahir);
            calTglLahir.setDate(tanggal);
        }catch(Exception e){
            e.printStackTrace();
            System.out.println("Error while showing Date");
        }
        
        if(jurusan.equals("SI")){
            cboJurusan.setSelectedIndex(0);
        } else{
            cboJurusan.setSelectedIndex(1);
        }
    }//GEN-LAST:event_tabelMahasiswaMouseClicked

