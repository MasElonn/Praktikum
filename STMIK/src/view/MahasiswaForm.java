    public void setKolomTabel(){
        TableColumn column = null;
        for(int i = 0;i<4;i++){
            column = tabelMahasiswa.getColumnModel().getColumn(i);
            switch(i){
                case 0 -> column.setPreferredWidth(60);
                case 1 -> column.setPreferredWidth(100);
                case 2 -> column.setPreferredWidth(100);
                case 3 -> column.setPreferredWidth(80);
                case 4 -> column.setPreferredWidth(20);
            }
        }
    }
    
    public void tampilData(){
        try{
            Connection c = KoneksiDB.getConnection();
            Statement s = c.createStatement();
            
            String query = "SELECT * FROM tbMahasiswa";
            ResultSet r = s.executeQuery(query);
            
            while(r.next()){
                
                Object[] o = new Object[5];
                o[0] = r.getString("nim");
                o[1] = r.getString("nama");
                o[2] = r.getString("tmpLahir");
                o[3] = r.getString("tglLahir");
                o[4] = r.getString("jurusan");
                
                model.addRow(Arrays.asList(o));
            }
        } catch (SQLException e){
            e.printStackTrace();
            System.out.println("Error while showing data");
        }
    }
    
    private java.sql.Date konversiDate(java.util.Date utilDate){
        java.sql.Date sqlDate = null;
        if(utilDate != null)
            sqlDate = new java.sql.Date(utilDate.getTime());
        return sqlDate;
    }
